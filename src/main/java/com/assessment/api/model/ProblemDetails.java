package com.assessment.api.model;

public class ProblemDetails {
    private String type;
    private String title;
    private int status;
    private String traceId;

    public String getType() {
        return type;
    }

    public String getTitle() {
        return title;
    }

    public int getStatus() {
        return status;
    }

    public String getTraceId() {
        return traceId;
    }
}
